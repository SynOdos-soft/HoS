export type TranslationKey = keyof typeof translations.en;
export type LanguageCode = keyof typeof translations;

/** Languages offered in Settings. */
export const LANGUAGES: Array<{ code: LanguageCode; label: string }> = [
  { code: 'en', label: 'English' },
  { code: 'fr', label: 'Français' },
  { code: 'el', label: 'Ελληνικά' },
];

/**
 * Translate a key. Unknown language or missing key falls back to English, so a
 * partially translated language is never worse than none.
 */
export const t = (key: TranslationKey, lang: string): string => {
  const language = translations[lang as LanguageCode] as Partial<Record<TranslationKey, string>> | undefined;
  return language?.[key] || translations.en[key];
};

/** True when the UI is not showing English, i.e. the disclaimer applies. */
export const isTranslated = (lang: string): boolean => lang !== 'en';

/**
 * date-fns locale for the active language, so weekday/month names in dates
 * follow the UI language rather than always English.
 */
export const dateLocaleFor = (lang: string): DateFnsLocale => {
  if (lang === 'fr') return frDateLocale;
  return enUSLocale;
};

// --- Reactive language store ----------------------------------------------
// Components call useT() instead of receiving a language prop, which keeps the
// dictionary usable deep in the tree without threading preferences everywhere.

let currentLanguage = 'en';
const subscribers = new Set<() => void>();

/** Subscribe to language changes (used by useT; exposed for tests). */
export const subscribeToLanguage = (fn: () => void): (() => void) => {
  subscribers.add(fn);
  return () => { subscribers.delete(fn); };
};

export const setI18nLanguage = (lang: string): void => {
  if (lang === currentLanguage) return;
  currentLanguage = lang;
  if (typeof document !== 'undefined') {
    document.documentElement.lang = lang;
    document.title = t('dashboard', lang);
  }
  subscribers.forEach(fn => {
    try { fn(); } catch { /* a bad listener must not break the switch */ }
  });
};

export const getI18nLanguage = (): string => currentLanguage;

/**
 * Returns a translator bound to the active language that re-renders the caller
 * when the language changes.
 */
export const useT = (): ((key: TranslationKey) => string) => {
  const [, bump] = useState(0);
  useEffect(() => subscribeToLanguage(() => bump(n => n + 1)), []);
  const lang = currentLanguage;
  return useCallback((key: TranslationKey) => t(key, lang), [lang]);
};